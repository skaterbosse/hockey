import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./LocalSport_Cloudflare_Scheduler_v4.js',import.meta.url),'utf8');
const {fixedMode,dynamicMode}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const d=s=>new Date(s);
assert.equal(fixedMode(d('2026-11-16T03:50:00Z')),'daily');
assert.equal(fixedMode(d('2026-07-16T02:50:00Z')),'daily');
assert.equal(fixedMode(d('2026-11-16T04:10:00Z')),'regular');
assert.equal(fixedMode(d('2026-11-16T12:00:00Z')),null);
const state={schemaVersion:2,generatedUTC:'2026-11-16T00:00:00Z',validUntilUTC:'2026-11-17T00:00:00Z',windows:[{kind:'live',dueUTC:'2026-11-16T01:02:00Z',expiresUTC:'2026-11-16T01:25:00Z',intervalMinutes:10},{kind:'highlights',dueUTC:'2026-11-16T01:10:00Z',expiresUTC:'2026-11-16T02:20:00Z',intervalMinutes:30}]};
for(const [time,expected] of [['01:00',null],['01:05','regular'],['01:10','regular'],['01:15','regular'],['01:20',null],['01:25',null],['01:40','regular'],['02:10','regular'],['02:40',null],['03:50','daily']]) assert.equal(dynamicMode(d(`2026-11-16T${time}:00Z`),state),expected);
assert.throws(()=>dynamicMode(d('2026-11-18T01:00:00Z'),state));
assert.throws(()=>dynamicMode(d('2026-11-16T01:00:00Z'),{...state,schemaVersion:1}));
assert.throws(()=>dynamicMode(d('2026-11-16T01:00:00Z'),{...state,windows:[{...state.windows[0],intervalMinutes:0}]}));
assert.equal(dynamicMode(d('2026-11-16T01:05:00Z'),{...state,windows:[]}),null);
console.log('18 worker assertions passed');
